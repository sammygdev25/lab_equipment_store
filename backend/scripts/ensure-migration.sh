#!/usr/bin/env bash
# Create the initial migration from the schema when no history exists, then the history is applied with
# prisma migrate deploy. Deterministic (prisma migrate diff, no database involved). Run from anywhere.
set -euo pipefail
cd "$(dirname "$0")/.."
if ls prisma/migrations/*/migration.sql >/dev/null 2>&1; then
  echo "[migrations] history present"
  exit 0
fi
mkdir -p prisma/migrations/0001_init
npx prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script > prisma/migrations/0001_init/migration.sql
printf '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n' > prisma/migrations/migration_lock.toml
echo "[migrations] created 0001_init from the schema"
